import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { build } from 'rolldown'

const root = new URL('../', import.meta.url)
const licenses = await Promise.all(
  ['hash-wasm', 'lz-string'].map(
    async (name) => `${name}\n${await readFile(new URL(`node_modules/${name}/LICENSE`, root), 'utf8')}`,
  ),
)
const cNotices = await Promise.all(
  ['argon2.c', 'blake2b.c'].map(async (name) => {
    const source = await readFile(new URL(`node_modules/hash-wasm/src/${name}`, root), 'utf8')
    return `hash-wasm/src/${name}\n${source.slice(source.indexOf('/*') + 2, source.indexOf('*/')).trim()}`
  }),
)
const notice = [...licenses, ...cNotices]
  .join('\n\n')
  .replace(/\r\n?/g, '\n')
  .replace(/[\t ]+$/gm, '')
const result = await build({
  input: fileURLToPath(new URL('agent/share.ts', root)),
  platform: 'node',
  resolve: { mainFields: ['module', 'main'] },
  // Keep only Argon2 and its embedded WASM when inlining the browser's dynamic import.
  plugins: [
    {
      name: 'argon2-only',
      resolveId: (id) => (id === 'hash-wasm' ? '\0argon2-only' : null),
      load: (id) =>
        id === '\0argon2-only'
          ? `export { argon2id } from ${JSON.stringify(fileURLToPath(new URL('node_modules/hash-wasm/dist/index.esm.js', root)))}`
          : null,
    },
  ],
  output: {
    format: 'esm',
    codeSplitting: false,
    minify: true,
    comments: { legal: false },
  },
  write: false,
})
if (result.output.length !== 1 || result.output[0].type !== 'chunk') throw new Error('Expected one standalone module.')
const chunk = result.output[0]
// Rolldown lists an inlined dynamic import as a self-reference in chunk metadata.
if (
  [...chunk.imports, ...chunk.dynamicImports].some(
    (specifier) => specifier !== chunk.fileName && !specifier.startsWith('node:'),
  )
)
  throw new Error('Standalone module has a non-builtin runtime dependency.')
const code = `/* raw-md standalone share SDK/CLI, Node.js 22+. Generated by npm run build:codec.\n\n${notice}\n*/\n${chunk.code}`
const bytes = Buffer.byteLength(code)
const sha256 = createHash('sha256').update(code).digest('hex')
const manifest = {
  formatVersion: 2,
  artifact: 'share.mjs',
  sha256,
  bytes,
  runtime: 'node >=22',
  sdkExports: ['createShareLink', 'readShareLink'],
  defaultBaseUrl: 'https://raw-md.pages.dev/',
  modes: ['plain', 'custom', 'secure'],
  maxSourceBytes: 4 * 1024 * 1024,
  maxPasswordBytes: 4096,
  checksum: 'share.mjs.sha256',
  licenseNotices: 'embedded in share.mjs',
}
for (const path of ['public/codec/v2/', 'skills/raw-md-export/scripts/']) {
  const directory = new URL(path, root)
  await mkdir(directory, { recursive: true })
  await writeFile(new URL('share.mjs', directory), code)
  await writeFile(new URL('share.mjs.sha256', directory), `${sha256}  share.mjs\n`)
}
await writeFile(new URL('public/codec/v2/manifest.json', root), `${JSON.stringify(manifest, null, 2)}\n`)
console.log(`Standalone share.mjs: ${bytes} bytes, sha256 ${sha256}`)
